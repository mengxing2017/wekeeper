import {render,screen,waitFor,fireEvent,cleanup} from '@testing-library/react'
import {QueryClient,QueryClientProvider} from '@tanstack/react-query'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {SourceAccess} from './index'
const api=vi.hoisted(()=>({list:vi.fn(),routes:vi.fn(),save:vi.fn(),remove:vi.fn(),associate:vi.fn(),revealSecret:vi.fn()}))
vi.mock('./api',()=>({sourceAccess:api}))
afterEach(()=>{cleanup();vi.resetAllMocks()})
beforeEach(()=>{api.list.mockResolvedValue({items:[{id:'key-1',unit_name:'运营单位',remark:'凭据备注',status:'active',revision:1,valid_from:'2026-01-01T00:00:00Z',valid_until:'2027-01-01T00:00:00Z'}],has_more:false});api.routes.mockResolvedValue({items:[{route_id:'m1',route_name:'路由一',remark:'路由备注',status:'active',revision:1}],has_more:false})})
it('separates credential and route remarks without a secret display',async()=>{
 const cache=new QueryClient({defaultOptions:{queries:{retry:false}}});cache.setQueryData(['source-admin','source-credentials',1,'','','',''],await api.list())
 render(<QueryClientProvider client={cache}><SourceAccess/></QueryClientProvider>)
 fireEvent.click(await screen.findByRole('button',{name:'详情 / 编辑'}))
 expect(await screen.findByRole('cell',{name:'路由备注'}, {timeout:15000})).toBeTruthy()
 expect((screen.getByLabelText('凭据备注') as HTMLTextAreaElement).value).toBe('凭据备注')
 expect(screen.getByRole('columnheader',{name:'凭据 ID（key_id）'})).toBeTruthy()
 expect(screen.queryByRole('columnheader',{name:'调用方 ID（source_id）'})).toBeNull()
 expect(screen.getByText('下游连接配置')).toBeTruthy()
 expect(screen.getByText('签名密钥（secret）')).toBeTruthy()
 expect(screen.getByText(/key_id 是唯一的调用方凭据 ID/)).toBeTruthy()
 expect(screen.queryByRole('textbox',{name:'签名密钥（secret）'})).toBeNull()
 expect(screen.getByRole('button',{name:'查看密钥'})).toBeTruthy()
 expect(api.revealSecret).not.toHaveBeenCalled()
 await waitFor(()=>expect(api.routes).toHaveBeenCalledWith('key-1',1))
})
it('creates caller credentials without a separate platform or downstream URL',async()=>{
 const cache=new QueryClient({defaultOptions:{queries:{retry:false}}})
 cache.setQueryData(['source-admin','source-credentials',1,'','','',''],{items:[],has_more:false})
 api.list.mockResolvedValue({items:[],has_more:false});api.save.mockResolvedValue({id:'key-new'})
 render(<QueryClientProvider client={cache}><SourceAccess/></QueryClientProvider>)
 expect(screen.getByText('调用方凭据')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:/新\s*增/}))
 fireEvent.change(await screen.findByLabelText('单位名称'),{target:{value:'Linjian 调用方'}})
 expect(screen.queryByLabelText('所属平台 ID')).toBeNull()
 expect(screen.queryByLabelText(/可信|路径前缀/)).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.save).toHaveBeenCalled(),{timeout:15000})
 const [kind,input,id]=api.save.mock.calls[0]
 expect(kind).toBe('source-credentials');expect(id).toBeUndefined()
 expect(input.unit_name).toBe('Linjian 调用方')
 expect(input.valid_until).toBeNull()
 expect(input).not.toHaveProperty('long_term')
 expect(input).not.toHaveProperty('source_id')
 expect(input).not.toHaveProperty('origins')
 expect(input).not.toHaveProperty('path_prefix')
})

it('manages routes inside one caller and authorizes new routes with its current credential',async()=>{
 const caller={id:'key-1',unit_name:'运营单位',status:'active',revision:7}
 api.list.mockImplementation(async(kind)=>({items:kind==='source-routes'?[{id:'route-1',route_name:'当前调用方路由',status:'active',revision:1}]:[caller],has_more:false}))
 api.save.mockResolvedValue({id:'route-new'});api.associate.mockResolvedValue({})
 const cache=new QueryClient({defaultOptions:{queries:{retry:false}}})
 cache.setQueryData(['source-admin','source-credentials',1,'','','',''],{items:[caller],has_more:false})
 render(<QueryClientProvider client={cache}><SourceAccess/></QueryClientProvider>)
 fireEvent.click(screen.getByRole('button',{name:'消息分发路由'}))
 expect(await screen.findByText('当前调用方路由',{}, {timeout:15000})).toBeTruthy()
 expect(api.list).toHaveBeenCalledWith('source-routes',1,'','','key-1')
 fireEvent.click(screen.getByRole('button',{name:'新增路由'}))
 fireEvent.change(await screen.findByLabelText('路由名称'),{target:{value:'新的业务路由'}})
 expect(screen.queryByLabelText('所属调用方')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.associate).toHaveBeenCalledWith('key-1','route-new',7,'active'),{timeout:15000})
 expect(api.save).toHaveBeenCalledWith('source-routes',expect.objectContaining({key_id:'key-1',route_name:'新的业务路由'}),undefined)
})

it('removes rotation and confirms permanent credential and child route deletion',async()=>{
 const cache=new QueryClient({defaultOptions:{queries:{retry:false}}})
 cache.setQueryData(['source-admin','source-credentials',1,'','','',''],await api.list())
 api.remove.mockResolvedValue({})
 render(<QueryClientProvider client={cache}><SourceAccess/></QueryClientProvider>)
 expect(screen.queryByRole('button',{name:/轮换/})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'删除凭据'}))
 expect(api.remove).not.toHaveBeenCalled()
 expect(await screen.findByText('将永久删除凭据及其消息分发路由，历史收件和任务保留。')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'确认删除'}))
 await waitFor(()=>expect(api.remove).toHaveBeenCalledWith('key-1'))
})
it('requires an expiry for bounded credentials and can change an existing credential to perpetual',async()=>{
 const cache=new QueryClient({defaultOptions:{queries:{retry:false}}})
 cache.setQueryData(['source-admin','source-credentials',1,'','','',''],await api.list())
 api.save.mockResolvedValue({})
 render(<QueryClientProvider client={cache}><SourceAccess/></QueryClientProvider>)
 fireEvent.click(screen.getByRole('button',{name:'详情 / 编辑'}))
 const expiry=await screen.findByLabelText('失效时间 UTC')
 fireEvent.change(expiry,{target:{value:''}})
 fireEvent.click(screen.getByRole('button',{name:/保\s*存/}))
 await screen.findByText(/请输入失效时间 UTC/,{},{timeout:15000})
 expect(api.save).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('checkbox',{name:'长期有效'}))
 await waitFor(()=>expect(screen.queryByLabelText('失效时间 UTC')).toBeNull(),{timeout:15000})
 fireEvent.click(screen.getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith('source-credentials',expect.objectContaining({valid_until:null,revision:1}),'key-1'))
})
