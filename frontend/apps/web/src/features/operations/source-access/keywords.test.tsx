import {cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import {QueryClient,QueryClientProvider} from '@tanstack/react-query'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {KeywordRules} from './keywords'
const api=vi.hoisted(()=>({list:vi.fn(),save:vi.fn()}))
vi.mock('./api',()=>({keywordRules:api}))
function show(){render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><KeywordRules/></QueryClientProvider>)}
beforeEach(()=>{api.list.mockResolvedValue({revision:3,filter_enabled:false,entries:[{word:'诈骗',enabled:true}]});api.save.mockResolvedValue({revision:4})})
afterEach(()=>{cleanup();vi.resetAllMocks()})
it('直接显示敏感词并保存新增',async()=>{
 show();expect(await screen.findByText('诈骗')).toBeTruthy()
 expect(screen.queryByText('发布历史')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name: /^添\s*加$/}))
 fireEvent.change(screen.getByLabelText('敏感词'),{target:{value:'违法'}})
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith({expected_revision:3,filter_enabled:false,entries:[{word:'诈骗',enabled:true},{word:'违法',enabled:true}]}))
})
it('编辑敏感词并保留并发版本',async()=>{
 show();await screen.findByText('诈骗')
 fireEvent.click(screen.getByRole('button',{name:/编\s*辑/}))
 fireEvent.change(screen.getByLabelText('敏感词'),{target:{value:'欺诈'}})
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith({expected_revision:3,filter_enabled:false,entries:[{word:'欺诈',enabled:true}]}))
})
it('启停敏感词时保存当前列表',async()=>{
 show();await screen.findByText('诈骗')
 fireEvent.click(screen.getByRole('switch',{name:'诈骗启用状态'}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith({expected_revision:3,filter_enabled:false,entries:[{word:'诈骗',enabled:false}]}))
})
it('确认后删除敏感词',async()=>{
 show();await screen.findByText('诈骗')
 fireEvent.click(screen.getByRole('button',{name:/删\s*除/}))
 fireEvent.click(await screen.findByRole('button',{name:'确认删除'}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith({expected_revision:3,filter_enabled:false,entries:[]}))
})
it('并发冲突时保留输入',async()=>{
 api.save.mockRejectedValue(new Error('记录已被修改，请刷新后重试'))
 show();await screen.findByText('诈骗')
 fireEvent.click(screen.getByRole('button',{name: /^添\s*加$/}))
 fireEvent.change(screen.getByLabelText('敏感词'),{target:{value:'新词'}})
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:/保\s*存/}))
 expect(await within(screen.getByRole('dialog')).findByText('记录已被修改，请刷新后重试')).toBeTruthy()
 expect((screen.getByLabelText('敏感词') as HTMLInputElement).value).toBe('新词')
})
it('默认全局停用，一次启用保留整个词库',async()=>{
 const entries=[{word:'诈骗',enabled:true},{word:'欺诈',enabled:false}]
 api.list.mockResolvedValue({revision:3,filter_enabled:false,entries})
 show();await screen.findByText('全局已停用')
 api.list.mockResolvedValue({revision:4,filter_enabled:true,entries})
 fireEvent.click(screen.getByRole('switch',{name:'全局启用敏感词拦截'}))
 await waitFor(()=>expect(api.save).toHaveBeenCalledWith({expected_revision:3,filter_enabled:true,entries}))
 expect(await screen.findByText('全局已启用')).toBeTruthy()
 fireEvent.change(screen.getByLabelText('搜索敏感词'),{target:{value:'不存在'}})
 api.list.mockResolvedValue({revision:5,filter_enabled:false,entries})
 fireEvent.click(screen.getByRole('switch',{name:'全局启用敏感词拦截'}))
 await waitFor(()=>expect(api.save).toHaveBeenLastCalledWith({expected_revision:4,filter_enabled:false,entries}))
 expect(await screen.findByText('全局已停用')).toBeTruthy()
})
it('全局切换保存失败保持原状态',async()=>{
 api.save.mockRejectedValue(new Error('保存失败'))
 show();await screen.findByText('全局已停用')
 fireEvent.click(screen.getByRole('switch',{name:'全局启用敏感词拦截'}))
 expect(await screen.findByText('保存失败')).toBeTruthy()
 expect(screen.getByRole('switch',{name:'全局启用敏感词拦截'}).getAttribute('aria-checked')).toBe('false')
})
it('读取失败不显示成全局已停用',async()=>{
 api.list.mockRejectedValue(new Error('读取失败'))
 show();expect(await screen.findByText('读取失败')).toBeTruthy()
 expect(screen.queryByText('全局已停用')).toBeNull()
 expect(screen.getByRole('switch',{name:'全局启用敏感词拦截'}).hasAttribute('disabled')).toBe(true)
})
it('旧编辑保留原全局开关和版本，冲突时不覆盖新配置',async()=>{
 show();await screen.findByText('诈骗')
 fireEvent.click(screen.getByRole('button',{name:/编\s*辑/}))
 api.list.mockResolvedValue({revision:4,filter_enabled:true,entries:[{word:'诈骗',enabled:true}]})
 fireEvent.click(screen.getByRole('switch',{name:'全局启用敏感词拦截'}))
 await screen.findByText('全局已启用')
 api.save.mockRejectedValue(new Error('版本冲突'))
 fireEvent.change(screen.getByLabelText('敏感词'),{target:{value:'修改词'}})
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:/保\s*存/}))
 await waitFor(()=>expect(api.save).toHaveBeenLastCalledWith({expected_revision:3,filter_enabled:false,entries:[{word:'修改词',enabled:true}]}))
 expect(await within(screen.getByRole('dialog')).findByText('版本冲突')).toBeTruthy()
 expect(screen.getByText('全局已启用')).toBeTruthy()
})
it('旧导入预览保留全局开关和版本，不能覆盖后续全局启用',async()=>{
 show();await screen.findByText('诈骗')
 const file=new File(['word,enabled\n新词,true'], 'words.csv',{type:'text/csv'})
 Object.defineProperty(file,'arrayBuffer',{value:async()=>new TextEncoder().encode('word,enabled\n新词,true').buffer})
 fireEvent.change(screen.getByLabelText('导入敏感词 CSV'),{target:{files:[file]}})
 await screen.findByText('确认导入')
 api.list.mockResolvedValue({revision:4,filter_enabled:true,entries:[{word:'诈骗',enabled:true}]})
 fireEvent.click(screen.getByRole('switch',{name:'全局启用敏感词拦截'}))
 await screen.findByText('全局已启用')
 api.save.mockRejectedValue(new Error('版本冲突'))
 fireEvent.click(screen.getByRole('button',{name:'确认导入'}))
 await waitFor(()=>expect(api.save).toHaveBeenLastCalledWith({expected_revision:3,filter_enabled:false,entries:[{word:'诈骗',enabled:true},{word:'新词',enabled:true}]}))
 expect(await screen.findByText('版本冲突')).toBeTruthy()
 expect(screen.getByText('全局已启用')).toBeTruthy()
})
