import {configure,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {QueryClient,QueryClientProvider} from '@tanstack/react-query'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {Advertising} from './index'
import {selectOption} from '../../../test/select-option'
const api=vi.hoisted(()=>({list:vi.fn(),create:vi.fn(),publish:vi.fn(),placements:vi.fn(),bind:vi.fn(),setState:vi.fn(),scopes:vi.fn()}))
vi.mock('./api',()=>({scopedMaterials:{list:api.list,create:api.create,publish:api.publish},adPlacements:{list:api.placements,create:api.bind,setState:api.setState},advertisingScopes:api.scopes,advertising:{},advertisementReasonLabels:{}}))
configure({asyncUtilTimeout:5000})
beforeEach(()=>{
 api.list.mockResolvedValue({items:[{id:'m1',revision:1,archived:false,content:{name:'广告甲',body:'广告内容',link:null}}],has_more:false})
 api.placements.mockResolvedValue({items:[],has_more:false})
 api.scopes.mockResolvedValue({platforms:[{id:'p1',name:'平台甲'}],units:[{id:'u1',platform_id:'p1',name:'单位甲'}]})
 api.create.mockResolvedValue({id:'new'});api.bind.mockResolvedValue({id:'binding'})
})
afterEach(()=>{cleanup();vi.resetAllMocks()})
function show(node:React.ReactNode){render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}>{node}</QueryClientProvider>)}
it('paginates ads, placements and drawer choices independently with named arrow buttons',async()=>{
 api.list.mockImplementation(async(page:number)=>({items:[{id:`m${page}`,revision:1,archived:false,content:{name:`广告第${page}页`,body:'广告内容',link:null}}],has_more:page===1}))
 api.placements.mockImplementation(async(page:number)=>({items:[],has_more:page===1}))
 show(<Advertising/>);await screen.findByText('广告第1页')
 expect((screen.getByRole('button',{name:'上一页广告'}) as HTMLButtonElement).disabled).toBe(true)
 const next=screen.getByRole('button',{name:'下一页广告'})
 expect(next.textContent).toBe('')
 fireEvent.click(next)
 await screen.findByText('广告第2页')
 expect(api.list).toHaveBeenCalledWith(2)
 expect(api.placements).not.toHaveBeenCalledWith(2)
 expect((screen.getByRole('button',{name:'下一页广告'}) as HTMLButtonElement).disabled).toBe(true)
 fireEvent.click(screen.getByRole('button',{name:'下一页投放绑定'}))
 await waitFor(()=>expect(api.placements).toHaveBeenCalledWith(2))
 fireEvent.click(screen.getByRole('button',{name:'绑定投放范围'}))
 await waitFor(()=>expect((screen.getByRole('button',{name:'下一页可选广告'}) as HTMLButtonElement).disabled).toBe(false))
 fireEvent.click(screen.getByRole('button',{name:'下一页可选广告'}))
 await waitFor(()=>expect((screen.getByRole('button',{name:'下一页可选广告'}) as HTMLButtonElement).disabled).toBe(true))
 expect((screen.getByRole('button',{name:'上一页可选广告'}) as HTMLButtonElement).disabled).toBe(false)
 // The drawer must not reset the page of either background list.
 expect((screen.getByRole('button',{name:'下一页广告',hidden:true}) as HTMLButtonElement).disabled).toBe(true)
 expect((screen.getByRole('button',{name:'下一页投放绑定',hidden:true}) as HTMLButtonElement).disabled).toBe(true)
})
it('manages scoped ads without workspace controls and validates 140 Unicode characters',async()=>{
 show(<Advertising/>);await screen.findByText('广告甲');fireEvent.click(screen.getByRole('button',{name: /^新\s*增$/}))
 fireEvent.change(await screen.findByLabelText('广告名称'),{target:{value:'新广告'}})
 fireEvent.change(screen.getByLabelText('广告正文'),{target:{value:'汉'.repeat(141)}})
 expect(screen.queryByLabelText('操作原因')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name: /^保\s*存$/}));await screen.findByText('单个广告正文最多 140 字');expect(api.create).not.toHaveBeenCalled()
 fireEvent.change(screen.getByLabelText('广告正文'),{target:{value:'😀'.repeat(140)}})
 fireEvent.click(screen.getByRole('button',{name: /^保\s*存$/}));await waitFor(()=>expect(api.create).toHaveBeenCalledWith({content:{name:'新广告',body:'😀'.repeat(140),link:null}}))
 expect(screen.queryByText('工作空间')).toBeNull()
})
it('binds an advertisement to a business unit without an operation reason',async()=>{
 show(<Advertising/>);await screen.findByText('广告甲')
 fireEvent.click(screen.getByRole('button',{name:'绑定投放范围'}))
 await selectOption(await screen.findByLabelText('选择广告'),'广告甲')
 await selectOption(screen.getByLabelText('选择平台'),'平台甲')
 await selectOption(screen.getByLabelText('选择业务单位'),'单位甲')
 fireEvent.change(screen.getByLabelText('生效时间'),{target:{value:'2026-11-15T00:00:00Z'}})
 expect(screen.queryByLabelText('操作原因')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name: /^保\s*存$/}))
 await waitFor(()=>expect(api.bind).toHaveBeenCalledExactlyOnceWith({material_id:'m1',scope:{kind:'unit',platform_id:'p1',unit_id:'u1'},enabled:true,valid_from:'2026-11-15T00:00:00.000Z',valid_until:null}))
})
