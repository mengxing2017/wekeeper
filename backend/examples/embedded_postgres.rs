use std::{net::SocketAddr, time::Duration};

use postgresql_embedded::{BOOTSTRAP_SUPERUSER, PostgreSQL, SettingsBuilder, V17};
use sqlx::postgres::PgPoolOptions;
use tracing::info;
use wekeeper_api::{observability, runtime};

const DATABASE_NAME: &str = "wekeeper_dev";

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    observability::init();
    let bind_addr = std::env::var("WEKEEPER_BIND_ADDR")
        .unwrap_or_else(|_| "127.0.0.1:8080".into())
        .parse::<SocketAddr>()?;
    if !bind_addr.ip().is_loopback() {
        return Err("embedded development API must bind to a loopback address".into());
    }

    // A random database port/password and fresh temporary data directory are
    // generated by the library. External WEKEEPER_DATABASE_* values are ignored.
    let settings = SettingsBuilder::new()
        .host("127.0.0.1")
        .port(0)
        .username(BOOTSTRAP_SUPERUSER)
        .temporary(true)
        .timeout(Some(Duration::from_secs(90)))
        .version(V17.clone())
        .build();
    let mut postgres = PostgreSQL::new(settings);
    info!("preparing temporary PostgreSQL 17; first run may download server binaries");
    postgres.setup().await?;
    postgres.start().await?;
    info!(
        database_port = postgres.settings().port,
        data_directory = %postgres.settings().data_dir.display(),
        "embedded PostgreSQL started; data will be removed on exit"
    );

    // Always stop PostgreSQL even when database creation, migration or HTTP bind
    // fails. Dropping PostgreSQL also removes its temporary data/password files.
    let result = run(&postgres, bind_addr).await;
    let stop_result = postgres.stop().await;
    result?;
    stop_result?;
    Ok(())
}

async fn run(
    postgres: &PostgreSQL,
    bind_addr: SocketAddr,
) -> Result<(), Box<dyn std::error::Error>> {
    postgres.create_database(DATABASE_NAME).await?;
    let pool = PgPoolOptions::new()
        .max_connections(5)
        .acquire_timeout(Duration::from_secs(5))
        .connect(&postgres.settings().url(DATABASE_NAME))
        .await?;
    let result = runtime::serve(pool.clone(), bind_addr).await;
    pool.close().await;
    result
}
